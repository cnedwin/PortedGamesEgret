// These IDs are the original smap picture numbers, after decoding the KYS layer value.
// Adjacent numbers usually share an art family. Unusual props keep their original art.
const covers = (id, start, end) => id >= start && id <= end;

export function submapEarthKind(id) {
  if (id <= 0) return 'void';
  if (covers(id, 154, 261) || id === 494 || id === 511) return 'water';
  if (covers(id, 306, 330) || covers(id, 544, 551) || covers(id, 579, 587) || id === 694) return 'carpet';
  if (covers(id, 336, 398) || covers(id, 469, 471)) return 'snow';
  if (id === 493 || covers(id, 621, 623)) return 'wood';
  if (covers(id, 479, 491) || id === 495 || covers(id, 512, 517) || covers(id, 565, 578)
    || covers(id, 588, 608) || covers(id, 624, 626) || covers(id, 679, 682) || covers(id, 695, 698)) return 'stone';
  if (covers(id, 637, 674)) return 'swamp';
  if (covers(id, 675, 678) || covers(id, 683, 693)) return 'cave';
  if (covers(id, 105, 153) || covers(id, 531, 543)) return 'sand';
  if (covers(id, 31, 34) || covers(id, 65, 69) || id === 497 || covers(id, 521, 530)) return 'dirt';
  return 'grass';
}

function artFamilies(rows) {
  const families = new Map();
  for (const [kind, ranges] of Object.entries(rows)) {
    for (const range of ranges) {
      const [first, last] = Array.isArray(range) ? range : [range, range];
      for (let id = first; id <= last; id++) families.set(id, kind);
    }
  }
  return families;
}

