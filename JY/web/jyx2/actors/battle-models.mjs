const portraitIds = new Map(battleModelGroups.flatMap(([, ids, headId]) => ids.map(id => [id, headId])));

export function battleModelFor({ id, headId }) {
  // Imported data can reuse a role number for another character.
  return portraitIds.get(id) === headId ? battleModels.get(id) : undefined;
}
