export function createRuntimeWords({language,wanted=[],onMissing}={}) {
  const languages=Object.keys(RUNTIME_WORDS);
  return createTextTable({languages:RUNTIME_WORDS,language:languages.includes(language)?language:pickLanguage(languages,wanted),
    fallback:'zh',...(onMissing?{onMissing}:{})});
}
