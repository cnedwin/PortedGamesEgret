import { readFile, writeFile } from 'node:fs/promises';
import { SourceTextModule } from 'node:vm';
import { makeGameImports, shippedGameFile } from '../src/browser-imports.mjs';

const folder = new URL('../', import.meta.url);
const mount = new URL('https://jy.invalid/JY/');
const virtualPlay = new URL('play/', mount);
const output = new URL('src/browser-startup-modules.mjs', folder);
const homeManifest = new URL('web/jyx2/home3d/scene.json', folder);
const manifests = JSON.parse(await readFile(new URL('vendor/importmap.json', folder), 'utf8'));
const imports = makeGameImports(manifests,
  (name, file) => new URL(`vendor/${name}/${file}`, mount).href,
  name => new URL(`third-party/${name}/index.js`, mount).href);

async function moduleGraph(entry, alreadyLoaded = new Set()) {
  const pending = [new URL(entry, virtualPlay)];
  const paths = new Set();
  for (const url of pending) {
    if (!url.href.startsWith(mount.href)) throw Error('Unexpected startup dependency ' + url.href);
    const path = url.href.slice(mount.href.length);
    if (paths.has(path) || alreadyLoaded.has(path)) continue;
    paths.add(path);
    const file = path.startsWith('play/') ? shippedGameFile(path.slice('play/'.length)) : path;
    const source = await readFile(new URL(file, folder), 'utf8');
    const parsed = new SourceTextModule(source, { identifier: path });
    const dependencies = parsed.moduleRequests?.map(request => request.specifier) ?? parsed.dependencySpecifiers;
    for (const specifier of dependencies) {
      const resolved = imports[specifier] ?? specifier;
      if (resolved === specifier && !/^(?:[./]|https?:)/.test(specifier)) {
        throw Error(`Unmapped startup dependency ${specifier} in ${path}`);
      }
      pending.push(new URL(resolved, url));
    }
  }
  return paths;
}

const paths = await moduleGraph('main.mjs');
const homeEntry = 'jyx2/scene/native-home-view.mjs';
const homePaths = await moduleGraph(homeEntry, paths);
// The import itself already starts the entry. Its dependencies are written to the post-click scene manifest.
homePaths.delete(`play/${homeEntry}`);
const text = [
  '// Generated by tools/generate-startup-preloads.mjs from the hosted entry and engine import map.',
  '// Only static imports are listed. The module script still owns execution and title readiness.',
  'export const startupModules = [',
  ...[...paths].map(path => '  ' + JSON.stringify(path) + ','),
  '];',
  '',
].join('\n');
const home = JSON.parse(await readFile(homeManifest, 'utf8'));
const homeHints = [...homePaths];
if (process.argv.includes('--check')) {
  const existing = (await readFile(output, 'utf8')).replace(/\r\n/g, '\n');
  if (existing !== text) throw Error('Run the startup preload generator after changing static imports.');
  if (JSON.stringify(home.modulePreloads) !== JSON.stringify(homeHints)) {
    throw Error('Run the startup preload generator after changing Home renderer imports.');
  }
} else {
  await writeFile(output, text);
  await writeFile(homeManifest, JSON.stringify({ ...home, modulePreloads: homeHints }, null, 2) + '\n');
}
console.log(`JY title module hints: ${paths.size}. Home module hints after Start: ${homePaths.size}.`);
