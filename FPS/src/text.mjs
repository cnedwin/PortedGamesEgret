/** The language to start in: the one asked for, else the browser's. */
export function pickLanguage(asked) {
  if (asked === 'zh' || asked === 'en') return asked;
  const browser = typeof navigator !== 'undefined' ? navigator.language || '' : '';
  return browser.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}
