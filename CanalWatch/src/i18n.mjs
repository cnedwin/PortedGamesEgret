export const words = createTextTable({ languages: WORDS, language: 'zh', fallback: 'zh' });

/** The words of `key` in the current language, with `{name}` filled from `values`. */
export const t = (key, values) => words.text(key, values);
export const getLanguage = () => words.language;
export const setLanguage = (language) => words.setLanguage(language === 'en' ? 'en' : 'zh');
/** Listen for a change of language; returns a function that stops listening. */
export const onLanguage = (listener) => words.onChange(listener);
/** The language a browser asking for `wanted` (a list such as `navigator.languages`) should start in. */
export const startLanguage = (wanted) => pickLanguage(['zh', 'en'], wanted);
