DOTS = {'.': (1.2, 0.7, 0.75, 2.6), '·': (1.2, 4.8, 0.7, 2.6), "'": None}


def outline(strokes, width):
    shape = unary_union([LineString(s).buffer(width / 2, cap_style='flat', join_style='mitre', mitre_limit=3) for s in strokes])
    return shape


def commands(shape):
    """The outline as Font3D pen commands: 0 starts a contour, 1 draws a line; holes are contours inside others."""
    out = []
    polygons = [shape] if shape.geom_type == 'Polygon' else list(shape.geoms)
    for polygon in polygons:
        for ring in [polygon.exterior, *polygon.interiors]:
            points = list(ring.coords)[:-1]
            for i, (x, y) in enumerate(points):
                out += [0 if i == 0 else 1, round(x * SCALE), round(y * SCALE + BASE)]
    return out


def main():
    glyphs = {}
    for char, strokes in HAN.items():
        glyphs[ord(char)] = {'advance': round(10.6 * SCALE), 'commands': commands(outline(strokes, 1.15))}
    for char, strokes in LATIN.items():
        glyphs[ord(char)] = {'advance': round(7.2 * SCALE), 'commands': commands(outline(strokes, 1.05))}
    for char, spec in DOTS.items():
        if spec is None:
            shape = outline([[(1.2, 9.6), (0.9, 7.4)]], 0.9)
            glyphs[ord(char)] = {'advance': round(2.4 * SCALE), 'commands': commands(shape)}
            continue
        x, y, r, advance = spec
        glyphs[ord(char)] = {'advance': round(advance * SCALE), 'commands': commands(Point(x, y).buffer(r, 3))}
    glyphs[ord(' ')] = {'advance': round(4 * SCALE), 'commands': []}
    font = {'unitsPerEm': UNITS, 'ascender': 880, 'descender': -160, 'lineHeight': 1250, 'familyName': 'Tea Horse Stone', 'glyphs': glyphs}
    path = ROOT / 'src' / 'art' / 'glyphs.json'
    path.write_text(json.dumps(font, separators=(',', ':')) + '\n')
    print(f'{len(glyphs)} glyphs into {path.relative_to(ROOT)} ({path.stat().st_size} bytes)')


if __name__ == '__main__':
    main()
