import { GpuParticles3D, Mesh3D, Trail3D, Water3D, createStandardMaterial3D } from '@egret/engine/world3d';
import { createBandit } from '../models/figures.mjs';

// The first water mirror uses its own tone mapping, depth and transmission, without the main view's shadows.
// Pick one real mesh per combination that first appears on the road, including hidden dust and distant flags.
function reflectionKind(mesh, material) {
  const geometry = mesh.geometry;
  const mapped = material.map && geometry.getAttribute('uv');
  if (mesh instanceof GpuParticles3D && mapped) return 'particles';
  if (mesh instanceof Trail3D && mapped) return 'trail';
  if (material.shading !== 'standard' || !geometry.getAttribute('normal')) return;
  if (mesh instanceof Water3D) return 'water';
  if (material.shader) return;
  if (material.splat) return 'terrain';
  const colored = material.vertexColors && geometry.getAttribute('color');
  const double = material.side === 'double';
  if (material.alphaMode === 'mask' && mapped && double && !colored) return 'flags';
  if (material.alphaMode === 'blend' && mapped && !double && !colored) return 'decals';
  if (material.alphaMode !== 'opaque') return;
  if (mapped && !colored) {
    if (double && !mesh.isInstanced) return 'canvas';
    if (!double) return mesh.isInstanced ? 'boards' : 'board';
  }
  if (!mapped && !double) {
    if (!mesh.isInstanced) return colored ? 'painted' : 'plain';
    if (colored) return mesh.instanceColors ? 'tinted-instances' : 'painted-instances';
  }
}

/** Prepare the costly first-use road programs, without drawing or putting a threat into the world. */
export async function prepareRoadPrograms(renderer, scene, camera, waters) {
  if (typeof renderer.preparePrograms !== 'function') return;
  const ford = waters.bodies.find(({ id }) => id === 'ford')?.water;
  if (!ford?.reflection) return;

  const reflection = ford.reflection.createPass(camera, [ford]);
  const lighting = { fog: Boolean(scene.fog), environment: Boolean(scene.environment) };
  const mirrors = new Map();
  scene.traverse((mesh) => {
    if (!(mesh instanceof Mesh3D) || mesh === ford) return;
    for (const material of Array.isArray(mesh.material) ? mesh.material : [mesh.material]) {
      if (!material.visible || material.isDisposed) continue;
      const kind = reflectionKind(mesh, material);
      if (kind && !mirrors.has(kind)) mirrors.set(kind, {
        mesh, material, reflection, ...lighting,
        ...(kind === 'water' ? { softDepth: true, transmission: true } : {})
      });
    }
  });

  // A decal generated by a wheel needs a mapped, blended program later. The board provides the
  // same position/normal/UV attributes and a texture without placing a decal or uploading its texture.
  const board = mirrors.get('board');
  const decal = !mirrors.has('decals') && board
    ? createStandardMaterial3D({ map: board.material.map, alphaMode: 'blend', depthWrite: false })
    : null;
  if (decal) mirrors.set('decals', { ...board, material: decal });

  // Both bandits and wolves use the same skinned, vertex-colored material variant.
  const { mesh, bundle } = createBandit();
  const requests = [
    ...mirrors.values(),
    { mesh, material: mesh.material, ...lighting, reflection },
    { mesh, material: mesh.material, ...lighting, receiveShadows: renderer.shadowsEnabled }
  ];
  if (renderer.shadowsEnabled) requests.push({ mesh, material: mesh.material, pass: 'shadow' });
  try {
    await renderer.preparePrograms(requests);
  } finally {
    mesh.geometry.dispose();
    bundle.geometry.dispose();
    decal?.dispose();
  }
}
