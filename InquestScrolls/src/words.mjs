/** A word in a language, with `{name}` filled from `values`. */
export function say(lang, key, values = {}) {
  const entry = WORDS[key];
  const text = entry ? entry[lang] ?? entry.zh : key;
  return text.replace(/\{(\w+)\}/g, (_, k) => String(values[k] ?? ''));
}
