import { createTextTable, pickLanguage } from '@egret/engine/kit';

const ZH_NUM = ['一', '二', '三', '四', '五', '六', '七', '八', '九'];
const ZH_HONOURS = ['東', '南', '西', '北', '紅中', '青發', '白板'];
const ZH_FLOWERS = ['春', '夏', '秋', '冬', '梅', '蘭', '竹', '菊'];
const EN_HONOURS = ['East', 'South', 'West', 'North', 'Red', 'Green', 'White'];
const EN_FLOWERS = ['Spring', 'Summer', 'Autumn', 'Winter', 'Plum', 'Orchid', 'Bamboo', 'Chrysanthemum'];

const tileWords = (language) => {
  const out = {};
  for (let kind = 0; kind < 42; kind++) {
    let name;
    if (language === 'zh') {
      if (kind < 27) name = ZH_NUM[kind % 9] + ['萬', '筒', '條'][Math.floor(kind / 9)];
      else if (kind < 34) name = ZH_HONOURS[kind - 27];
      else name = ZH_FLOWERS[kind - 34];
    } else if (kind < 27) name = `${(kind % 9) + 1} ${['Characters', 'Dots', 'Bamboo'][Math.floor(kind / 9)]}`;
    else if (kind < 34) name = kind < 31 ? `${EN_HONOURS[kind - 27]} Wind` : `${EN_HONOURS[kind - 27]} Dragon`;
    else name = EN_FLOWERS[kind - 34];
    out['tile' + kind] = name;
  }
  return out;
};

