// Build-time-only packing of the original game and its official vendored engine.
// Use esbuild 0.28.2 (`ESBUILD` may be an absolute path to its JS module).
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const read = file => readFileSync(path.join(root, file));
const entry = 'src/main.mjs', output = 'assets/five-regiments.mjs', index = 'index.html', manifestFile = 'assets/five-regiments.json';
const version = '0.28.2';
const slash = s => s.split(path.sep).join('/');
const sourceName = file => slash(path.relative(root, file));
// Git's checkout EOL policy varies by platform. Everything in this build graph is UTF-8
// source text; hash the canonical LF form rather than the working tree's CRLF choice.
export const canonicalText = bytes => Buffer.from(bytes.toString('utf8').replace(/\r\n/g, '\n'));
const sha = bytes => createHash('sha256').update(canonicalText(bytes)).digest('hex');
const html = read(index).toString();
const importMap = JSON.parse(/<script type="importmap">([\s\S]*?)<\/script>/.exec(html)[1]);
const vendorMap = JSON.parse(read('vendor/importmap.json'));
if (JSON.stringify(importMap) !== JSON.stringify(vendorMap)) throw Error('Page and vendor import maps disagree.');

// Source-relative resource URLs must stay relative to the ORIGINAL module, not the packed entry.
// This game has two meta-URL callers. The stage's one bare import.meta.resolve uses the unchanged
// global page import map to tell the separately loaded sky worker the actual engine URL.
function relocateMeta(file, code) {
  if (!/\bimport\.meta\b/.test(code)) return code;
  if (!['src/main.mjs', 'src/view/stage.mjs'].includes(file))
    throw Error('New import.meta usage requires a URL audit: ' + file);
  const rest = code.replaceAll('import.meta.url', '');
  if (/\bimport\.meta\b/.test(rest) && (file !== 'src/view/stage.mjs' ||
      /\bimport\.meta\b/.test(rest.replaceAll("import.meta.resolve('@egret/engine/world3d')", '').replaceAll('typeof import.meta.resolve', ''))))
    throw Error('New import.meta resolution requires a URL audit: ' + file);
  const original = '../' + file;
  return code.replaceAll('import.meta.url', `(new URL(${JSON.stringify(original)}, import.meta.url).href)`);
}

function digest(paths) {
  const hash = createHash('sha256');
  // The sky projection worker is intentionally a separate URL, not an extra entry in the
  // browser bundle. Audit its source too, so a worker change cannot silently stale metadata.
  for (const file of [...new Set([...paths, 'src/view/sky-worker.mjs', 'tools/bundle.mjs', 'package.json', 'package-lock.json'])].sort())
    hash.update(file).update('\0').update(canonicalText(read(file)));
  return hash.update(JSON.stringify(importMap)).digest('hex');
}

function pageForBundle(source) {
  const result = source.replace(/  <!-- Generated startup modules: tools\/preload-modules\.mjs -->[\s\S]*?  <!-- End generated startup modules -->\r?\n/, '')
    .replace(/<script type="module" src="(?:src\/main\.mjs|(?:build|assets)\/five-regiments\.mjs)"><\/script>/, `<script type="module" src="${output}"></script>`);
  if (!result.includes(`<script type="module" src="${output}"></script>`)) throw Error('Missing game module entry.');
  return result;
}

function check() {
  const manifest = JSON.parse(read(manifestFile));
  if (manifest.esbuild !== version || digest(manifest.inputs) !== manifest.sourceSha256 || sha(read(output)) !== manifest.outputSha256 ||
      manifest.bytes !== canonicalText(read(output)).length || pageForBundle(html) !== html)
    throw Error('Stale bundled launch entry; rebuild using esbuild ' + version);
  console.log(`${manifest.inputs.length} modules, ${manifest.bytes} bytes, integrity verified`);
}

async function build() {
  const supplied = process.env.ESBUILD;
  const api = await import(supplied && path.isAbsolute(supplied) ? pathToFileURL(supplied).href : supplied ?? 'esbuild');
  const esbuild = api.default ?? api;
  if (esbuild.version !== version) throw Error(`Expected esbuild ${version}, got ${esbuild.version}`);
  const result = await esbuild.build({
    absWorkingDir: root, entryPoints: [entry], outfile: output, write: false, metafile: true,
    bundle: true, format: 'esm', platform: 'browser', minify: true, keepNames: true, target: 'es2022',
    preserveSymlinks: true, legalComments: 'none',
    banner: { js: '/*! Imperial Arena with Egret Rebuild (Apache-2.0). Source: src/ and vendor/; licences: vendor/NOTICE, vendor/SOURCE.md. Generated by tools/bundle.mjs. */' },
    plugins: [{ name: 'game-import-map-and-resource-urls', setup(build) {
      build.onResolve({ filter: /^[^./]/ }, args => {
        if (args.kind === 'entry-point') return;
        const mapped = importMap.imports[args.path];
        return mapped ? { path: path.resolve(root, mapped) } : { errors: [{ text: 'Unmapped startup import ' + args.path }] };
      });
      build.onLoad({ filter: /\.(mjs|js)$/ }, args => ({
        contents: relocateMeta(sourceName(args.path), readFileSync(args.path, 'utf8')), loader: 'js', resolveDir: path.dirname(args.path)
      }));
    }}]
  });
  if (result.outputFiles.length !== 1) throw Error('Expected exactly one browser module.');
  const bytes = canonicalText(Buffer.from(result.outputFiles[0].contents));
  const inputs = Object.keys(result.metafile.inputs).map(name => slash(name)).sort();
  if (inputs.some(name => name.startsWith('../') || path.isAbsolute(name))) throw Error('Bundle input outside the game.');
  const manifest = { esbuild: version, inputs, sourceSha256: digest(inputs), outputSha256: sha(bytes), bytes: bytes.length };
  mkdirSync(path.dirname(path.join(root, output)), { recursive: true });
  writeFileSync(path.join(root, output), bytes);
  writeFileSync(path.join(root, manifestFile), JSON.stringify(manifest, null, 2) + '\n');
  writeFileSync(path.join(root, index), pageForBundle(html));
  console.log(`${inputs.length} modules bundled in ${bytes.length} bytes`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) check(); else await build();
}
