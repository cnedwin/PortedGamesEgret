// One table per language, each falling back to Chinese for a word it lacks; `{name}` is filled by the table.
const tables = {
  zh: createTextTable({ languages: WORDS, language: 'zh' }),
  en: createTextTable({ languages: WORDS, language: 'en', fallback: 'zh' })
};

/** A line in a language, with `{name}` filled from `values`. */
export function say(lang, key, values = {}) {
  return (tables[lang] ?? tables.zh).text(key, values);
}

