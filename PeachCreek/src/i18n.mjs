export const words = createTextTable({ languages: WORDS, language: 'zh', fallback: 'zh' });
export const t = (key, values) => words.text(key, values);
export const getLanguage = () => words.language;
export const setLanguage = (language) => words.setLanguage(language === 'en' ? 'en' : 'zh');
export const onLanguage = (listener) => words.onChange(listener);
export const startLanguage = (wanted) => pickLanguage(['zh', 'en'], wanted);

/** Names for keys that share a word with a resource. */
export const buildingName = (kind) => t({ mulberry: 'mulberry_b', clay: 'clay_n', iron: 'iron_n' }[kind] ?? kind);
export const buildingAbout = (kind) => t('about_' + ({ mulberry: 'mulberry_b', clay: 'clay_n', iron: 'iron_n' }[kind] ?? kind));

/** A duration in words. */
export function duration(seconds) {
  const s = Math.max(0, Math.round(seconds));
  if (s >= 3600) return t('hours', { h: Math.floor(s / 3600), m: Math.floor((s % 3600) / 60) });
  if (s >= 60) return t('minutes', { m: Math.floor(s / 60), s: s % 60 });
  return t('seconds', { s });
}

/** A big number shortened: 12,345 / 1.2万 or 1.2M. */
export function amount(n) {
  const v = Math.floor(n);
  if (getLanguage() === 'zh') {
    if (v >= 1e8) return (v / 1e8).toFixed(v >= 1e9 ? 0 : 1) + '亿';
    if (v >= 1e4) return (v / 1e4).toFixed(v >= 1e5 ? 0 : 1) + '万';
    return String(v);
  }
  if (v >= 1e6) return (v / 1e6).toFixed(v >= 1e7 ? 0 : 1) + 'M';
  if (v >= 1e4) return (v / 1e3).toFixed(v >= 1e5 ? 0 : 1) + 'k';
  return v.toLocaleString('en-US');
}
